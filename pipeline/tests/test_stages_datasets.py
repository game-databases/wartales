def test_ac2_iii_analog_corrupted_cdb_copy_gates_before_canonical_write(
        regen, tmp_path):
    """AC2(ii)'s tool-level analog: a corrupted data.cdb COPY driven through
    the step-1..3 chain exits nonzero at the gate with the canonical plane
    (stand-in sentinel) byte+mtime untouched. The seed drops one `item`
    line — emit survives it, and the gate catches it against the verifier's
    frozen doc-side census transcription (2124 rows != census 2125)."""
    bad_cdb = tmp_path / "data.cdb"
    db = json.loads(regen["cdb"].read_text(encoding="utf-8"))
    for s in db["sheets"]:
        if s["name"] == "item":
            assert len(s["lines"]) == CENSUS_PER_KIND["item"]
            del s["lines"][1]                        # the seeded corruption
    bad_cdb.write_text(json.dumps(db, ensure_ascii=False), encoding="utf-8")

    draft, rel = tmp_path / "d", tmp_path / "r"
    ran = []
    for wave in ("wave1", "wave2"):                  # steps 1–2 regenerate
        r = _run([TOOLS / "cdb_emit.py", bad_cdb, "--wave", wave,
                  "--outdir", draft, "--reldir", rel])
        ran.append(r.returncode)
    canonical = tmp_path / "canonical"               # stand-in for extracted/
    canonical.mkdir()
    sentinel = canonical / ".sentinel"
    sentinel.write_text("untouched", encoding="utf-8")
    before = sentinel.stat().st_mtime_ns

    gate = _run([TOOLS / "cdb_verify.py", bad_cdb,       # step 3 GATE
                 "--datadir", draft, "--reldir", rel])
    assert gate.returncode == 1, "gate did NOT catch the seeded corruption"
    assert "rows != census" in gate.stdout           # drift named against the
                                                     # frozen transcription
    assert sentinel.read_text(encoding="utf-8") == "untouched"
    assert sentinel.stat().st_mtime_ns == before         # canonical untouched
    assert ran.count(0) == 2                             # regen itself succeeded


