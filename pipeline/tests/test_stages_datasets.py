    assert table.get("skill@__ignoreLoc__") == PRESERVED_SKILL_IGNORELOC == 40
    levels = {k.split("@")[-1]: v for k, v in table.items()
              if k.startswith("skill@levels@")}
    assert levels == PRESERVED_LEVELS_BREAKDOWN
    assert sum(levels.values()) == PRESERVED_LEVELS_OCCURRENCES == 14
    assert len(levels) == PRESERVED_LEVELS_DISTINCT_KEYS == 9
    assert sum(table.values()) == PRESERVED_PACK_TOTAL == 133

    gate = _gate(regen, regen["draft"], regen["rel"])
    m = re.search(r"undeclared payload keys preserved verbatim:\s*(\d+)",
                  gate.stdout)
