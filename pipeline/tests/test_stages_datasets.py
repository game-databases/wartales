def _mod(name):
    """Import a PROVEN pipeline tool module (these exist and are pinned)."""
    import importlib
    try:
        return importlib.import_module(name)
    except ModuleNotFoundError as exc:
        pytest.skip(f"proven tool module {name} unavailable: {exc}")


