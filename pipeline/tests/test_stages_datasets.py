def _run(cmd, timeout=600):
    """Run a pipeline tool through its CLI contract; capture text output."""
    return subprocess.run(
        [sys.executable, *[str(c) for c in cmd]],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=timeout,
    )


def _need_new_tool(name):
    """Skip green while a stage-4–6 module hasn't landed (blind parallel
    build: this suite never imports or reads those files)."""
    if not (TOOLS / name).exists():
        pytest.skip(
            f"pipeline/tools/{name} absent — CodeWriter side of the blind "
            "build hasn't landed yet; suite arms itself automatically"
        )


def _jsonl_rows(path):
    """Data lines (everything after the `_meta` header) of a dataset file."""
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    return lines[1:]


def _jsonl_meta(path):
    return json.loads(Path(path).read_text(encoding="utf-8").splitlines()[0])["_meta"]


def _pair_edges(path):
    """(meta, edges) of a relink pair file."""
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    return json.loads(lines[0])["_meta"], [json.loads(x) for x in lines[1:]]


